"""Generate the exam wiki from exam.db.

Layout (see wiki/SCHEMA.md):

  wiki/raw/corpus/questions.md     immutable export, hash-pinned
  wiki/raw/corpus/transcripts.md   immutable export, hash-pinned
  wiki/entities/<concept>.md       one page per GCP service/feature
  wiki/index.md                    sectioned catalog
  wiki/log.md                      append-only action log

Two invariants this script enforces, both learned by measuring the corpus:

1. Concept links come from the WRITTEN slide text (stem + options). The
   transcript names a printed concept only ~23-60% of the time, so it is never
   used to decide which question "belongs" to a concept.
2. Every transcript quote is prefixed `[ASR]`. The captions mangle product names
   (IAM -> "IM", "DCS Run", "Dataf Flow"), so the wording must never look like
   the exam's own text.

Usage:
    python scripts/build_wiki.py [--db exam/exam.db] [--wiki wiki]
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_concepts import build_pattern  # single source of truth for alias matching

TODAY = dt.date.today().isoformat()

# Sentences that explain a specific option, so a page can show WHY the wrong
# answers are wrong without inventing anything.
OPTION_RE = re.compile(
    r"\b(?:option|choice|answer)\s+([A-E])\b"          # "option C"
    r"|\b([A-E])\s+(?:is|would be|does|doesn't|isn't|would not)\b",  # "C is"
    re.IGNORECASE)


def slugify(name: str) -> str:
    s = name.lower()
    s = s.replace("/", "-").replace(".", "")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s


def sentences(text: str) -> list[str]:
    text = " ".join((text or "").split())
    parts = re.split(r"(?<=[.!?])\s+", text)
    return [p.strip() for p in parts if len(p.strip()) > 12]


def hash_body(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def write_raw(path: Path, body: str, source_note: str) -> None:
    digest = hash_body(body)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "---\n"
        f"source: {source_note}\n"
        f"ingested: {TODAY}\n"
        f"sha256: {digest}\n"
        "---\n\n" + body, encoding="utf-8")


def conf_for(concept: dict) -> str:
    n = concept["n_questions"]
    if n >= 3 and any(q["in_stem"] for q in concept["questions"]):
        return "high"
    if n >= 2:
        return "medium"
    return "low"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="exam/exam.db")
    ap.add_argument("--wiki", default="wiki")
    ap.add_argument("--concepts", default="work/concepts.json")
    args = ap.parse_args()

    wiki = Path(args.wiki)
    data = json.loads(Path(args.concepts).read_text(encoding="utf-8"))
    concepts = data["concepts"]

    conn = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    qrows = {r["label"]: r for r in conn.execute("SELECT * FROM questions")}
    qid_to_label = {r["id"]: r["label"] for r in conn.execute("SELECT id, label FROM questions")}
    # question label -> concept names (for cross-links), independent of any page
    label_concepts: dict[str, list[str]] = defaultdict(list)
    for cname, cid in conn.execute("SELECT name, id FROM concepts"):
        for (label,) in conn.execute(
                "SELECT q.label FROM question_concepts qc JOIN questions q ON q.id=qc.question_id"
                " WHERE qc.concept_id=?", (cid,)):
            label_concepts[label].append(cname)
    dup_map = {r["label"]: r["keeper_number"] for r in conn.execute(
        "SELECT q.label, k.number AS keeper_number FROM questions q"
        " JOIN questions k ON k.id = q.duplicate_of")}
    conn.close()

    # ---------------------------------------------------------------- raw layer
    q_body = ["# Question bank (exported from exam/exam.db)", "",
              "Slide text and answers are the source of record. `correct` comes from",
              "green-pixel detection on the reveal frame, not from the narration.", ""]
    t_body = ["# Walkthrough transcripts (exported from exam/exam.db)", "",
              "Autogenerated speech-to-text between one question and the next.",
              "Wording is unreliable; product names are frequently mangled.", ""]
    for label, r in sorted(qrows.items(), key=lambda kv: (kv[1]["number"] is None, kv[1]["number"] or 0)):
        num = r["number"]
        heading = f"## Q{num} ({label})" if num else f"## {label} (unnumbered)"
        q_body += [heading, "",
                   f"- video: {r['video_id']}  t={r['t_answer']}s",
                   f"- watch: {r['watch_url']}",
                   f"- image: Questions/auto/{r['image']}",
                   f"- answer: {r['correct'] or '(none detected)'}"
                   + (f"  (choose {r['choose']})" if r["choose"] else ""),
                   "", "**Question.** " + " ".join((r["stem"] or "").split()), ""]
        for o in json.loads(r["options_json"] or "[]"):
            mark = "**✓**" if o["green_px"] > 0 else " "
            q_body.append(f"  - {mark} {o['letter']}. " + " ".join((o.get("text") or "").split()))
        q_body.append("")
        t_body += [heading, "", (r["explanation"] or "(no transcript)").strip(), ""]
    write_raw(wiki / "raw/corpus/questions.md", "\n".join(q_body), "exam/exam.db questions")
    write_raw(wiki / "raw/corpus/transcripts.md", "\n".join(t_body), "exam/exam.db questions.explanation")

    # --------------------------------------------------------------- page layer
    ent = wiki / "entities"
    ent.mkdir(parents=True, exist_ok=True)
    made = []
    for concept in concepts:
        name = concept["name"]
        slug = slugify(name)
        qs = concept["questions"]
        labels = [q["label"] for q in qs]

        # Teaching sentences: only from the transcripts of questions that PRINT
        # the concept, and only sentences that actually name it. Matching on the
        # first word of the name is not enough - almost every product starts with
        # "Cloud", so "Cloud Load Balancing" would otherwise quote sentences about
        # Cloud Logging. Reuse the same alias patterns the index was built with.
        pats = [build_pattern(a) for a in ([name] + list(concept.get("aliases") or []))]
        teaching: list[tuple[int, str]] = []
        traps: list[tuple[int, str]] = []
        for q in qs:
            row = qrows.get(q["label"])
            if not row or not row["explanation"]:
                continue
            sents = sentences(row["explanation"])
            num = q["number"] if q["number"] else 0
            for s in sents:
                if any(p.search(s) for p in pats) and len(teaching) < 40:
                    teaching.append((num, s))
            # The reason a wrong option is wrong usually sits in the NEXT
            # sentence ("Let's look at option C, which suggests... It requires you
            # to manage your own infrastructure..."), so keep the pair.
            for i, s in enumerate(sents):
                if OPTION_RE.search(s):
                    pair = s if i + 1 >= len(sents) else f"{s} {sents[i + 1]}"
                    traps.append((num, " ".join(pair.split())[:320]))
        seen = set()
        teaching = [t for t in teaching
                    if not (t[1][:60] in seen or seen.add(t[1][:60]))][:6]
        traps = traps[:8]

        # cross-links: concepts sharing the most questions with this one
        counts = defaultdict(int)
        for label in labels:
            for other in label_concepts[label]:
                if other != name:
                    counts[other] += 1
        related = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:4]
        same_cat = False
        if len(related) < 2:
            # The schema requires >=2 outbound links. Top up with the busiest
            # concepts in the bank that are not already linked, and label the
            # section so the weaker link is visible rather than passed off as a
            # shared-question link.
            have = {r for r, _ in related}
            pool = sorted(((c["n_questions"], c["name"]) for c in concepts
                           if c["name"] != name and c["name"] not in have),
                          reverse=True)
            related += [(n, 0) for _, n in pool[: 2 - len(related)]]
            same_cat = True

        fm = [
            "---",
            f"title: {name}",
            f"created: {TODAY}",
            f"updated: {TODAY}",
            "type: entity",
            f"tags: [{concept['category']}, service, "
            + ("high-frequency]" if concept["n_questions"] >= 15 else "exam-topic]"),
            "sources: [raw/corpus/questions.md, raw/corpus/transcripts.md]",
            "questions: [" + ", ".join(str(q["number"]) for q in qs if q["number"]) + "]",
            f"confidence: {conf_for(concept)}",
            "---",
        ]
        lines = fm + ["", f"# {name}", "",
                      f"*{concept['n_questions']} question(s) in the bank print this concept"
                      f" — part of tag `{concept['category']}`.*", ""]
        if teaching:
            lines += ["## Teaching from the walkthrough", "",
                      "> Transcripts are autogenerated; names are frequently mangled.", ""]
            for num, s in teaching:
                lines.append(f"- **Q{num}** — [ASR] {s}")
            lines.append("")
        else:
            lines += ["## Teaching from the walkthrough", "",
                      "No transcript in the corpus names this concept, so there is no "
                      "spoken teaching to quote. The linkage below is from the printed "
                      "slide text only.", ""]
        lines += ["## Questions that test it", "",
                  "| Q | printed in | watch |", "|---|---|---|"]
        for q in qs:
            where = []
            if q["in_stem"]:
                where.append("stem")
            if q["in_options"]:
                where.append("options")
            num = q["number"] if q["number"] else "—"
            if q["label"] in dup_map:
                num = f"{num} (= {dup_map[q['label']]})"
            lines.append(f"| {num} | {', '.join(where) or '—'} | [{q['label']}]({q['watch_url']}) |")
        lines.append("")
        if traps:
            lines += ["## Traps in these questions", "",
                      "What the walkthrough says about the options that are not the answer:",
                      ""]
            for num, s in traps:
                lines.append(f"- **Q{num}** — [ASR] {s}")
            lines.append("")
        if related:
            if same_cat:
                lines += ["## Links", "",
                          "No question in the bank shares this concept with another, so"
                          " these are the busiest concepts in this bank:",
                          " ".join(f"[[{slugify(r)}|{r}]]" for r, _ in related), ""]
            else:
                lines += ["## Links", "",
                          "Questions these share the most ground with:",
                          " ".join(f"[[{slugify(r)}|{r}]] ({n} shared)" for r, n in related), ""]
        (ent / f"{slug}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        made.append({"name": name, "slug": slug, "category": concept["category"],
                     "n": concept["n_questions"], "confidence": conf_for(concept),
                     "related": [r for r, _ in related]})

    # ------------------------------------------------------------ index and log
    # Hand-written concept (trap) pages are owned by you, so they are never
    # regenerated - but the generator owns index.md, so it must carry them over.
    concept_dir = wiki / "concepts"
    concept_pages = []
    for p in sorted(concept_dir.glob("*.md")) if concept_dir.exists() else []:
        txt = p.read_text(encoding="utf-8")
        m = re.search(r"^title:\s*(.+)$", txt, re.M)
        concept_pages.append((p.stem, m.group(1).strip() if m else p.stem))
    by_cat = defaultdict(list)
    for m in made:
        by_cat[m["category"]].append(m)
    idx = ["# Wiki Index", "",
           "> Content catalog. Read this first to find pages for a query.",
           f"> Last updated: {TODAY} | Total pages: {len(made)} entities + "
           f"{len(concept_pages)} concepts", ""]
    if concept_pages:
        idx += ["## Concepts and traps", ""]
        for slug, title in concept_pages:
            idx.append(f"- [[{slug}|{title}]]")
        idx.append("")
    for cat in sorted(by_cat):
        idx += [f"## {cat.title()} ({len(by_cat[cat])})", ""]
        for m in sorted(by_cat[cat], key=lambda x: x["name"].lower()):
            idx.append(f"- [[{m['slug']}|{m['name']}]] — {m['n']} question(s), confidence {m['confidence']}")
        idx.append("")
    (wiki / "index.md").write_text("\n".join(idx), encoding="utf-8")

    log = wiki / "log.md"
    if not log.exists():
        log.write_text("# Wiki Log\n\n> Chronological record of wiki actions. Append-only.\n"
                       "> Format: `## [YYYY-MM-DD] action | subject`\n", encoding="utf-8")
    with log.open("a", encoding="utf-8") as fh:
        fh.write(f"\n## [{TODAY}] create | Wiki seeded from exam.db\n")
        fh.write(f"- Pages created: {len(made)} entity pages in `entities/`\n")
        fh.write("- Raw sources exported: `raw/corpus/questions.md`, "
                 "`raw/corpus/transcripts.md` (hash-pinned)\n")
        fh.write(f"- Concept linkage derived from printed slide text only; "
                 f"{len(made)} concepts with >=1 question\n")
        fh.write(f"- Hand-written concept pages carried over: {len(concept_pages)}"
                 + (f" ({', '.join(s for s, _ in concept_pages)})" if concept_pages else "")
                 + "\n")
        fh.write("- Repeated questions flagged in exam.db (`duplicate_of`) so an exam"
                 " cannot ask the same question twice\n")

    print(f"# entities written: {len(made)} -> {ent}")
    print(f"# raw sources: raw/corpus/questions.md, raw/corpus/transcripts.md")
    print(f"# index.md: {len(made)} pages across {len(by_cat)} categories")
    print(f"# log.md appended")
    return 0


if __name__ == "__main__":
    sys.exit(main())
